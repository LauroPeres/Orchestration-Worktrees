"""The merged `.claude/` and `CLAUDE.md` of a wt folder: files, links and the manifest (SPEC §29).

The merge rules live in `wt.claudemerge` (pure); this module reads the repos, writes what the
merge produced and keeps `.claude/.wt-generated.json` so a later run, or `remove`, touches
exactly the files wt made and nothing else.
"""

import hashlib
import json
import os
import stat
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from typing import Any, Literal

from wt.claudemerge import (
    HOOK_SCRIPT,
    HOOK_SCRIPT_NAME,
    Conflict,
    RepoClaude,
    SettingsMerge,
    merge_agent,
    merge_settings,
    prefixed,
    render_claude_md,
)
from wt.errors import WtError
from wt.state import atomic_write

MANIFEST_VERSION = 1
CLAUDE_DIR = ".claude"
CLAUDE_MD = "CLAUDE.md"
MANIFEST_REL = f"{CLAUDE_DIR}/.wt-generated.json"
MIN_REPOS = 2
FILE_MODE = 0o644
EXECUTABLE_MODE = 0o755
SKILL_FILE = "SKILL.md"
FRONTMATTER_FENCE = "---"

Kind = Literal["copy", "link", "file"]


@dataclass(frozen=True)
class ClaudeSyncResult:
    changed: bool
    folder: Path
    repos: list[str]
    agents: list[str]
    skills: list[str]
    conflicts: list[Conflict]
    notes: list[str]


@dataclass(frozen=True)
class _Entry:
    """What wt wants at one relative path. For a link, `data` is the link target."""

    kind: Kind
    data: bytes
    source: str
    mode: int = FILE_MODE


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _foreign(path: Path) -> WtError:
    return WtError(f"{path} exists and was not generated by wt; move it away or set claude: false")


def _contained(folder: Path, rel: str) -> Path:
    """`folder/rel`, refusing a path whose parent folders lead out of `folder`."""
    path = folder / rel
    if not path.parent.resolve().is_relative_to(folder.resolve()):
        raise WtError(f"{path} would be outside {folder}; refusing to touch it.")
    return path


# --- manifest ---------------------------------------------------------------------------------


def _parse_manifest(path: Path) -> tuple[str, dict[str, str]]:
    """(wt name, {relative path: sha256}) of a manifest file."""
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
        files = {rel: str(info["sha256"]) for rel, info in raw["files"].items()}
        name = str(raw["wt"])
    except (ValueError, OSError, KeyError, TypeError, AttributeError) as exc:
        raise WtError(
            f"{path} is corrupt or unreadable ({exc.__class__.__name__}); "
            "delete it and the generated files by hand."
        ) from exc
    for rel in files:
        parts = PurePosixPath(rel).parts
        if PurePosixPath(rel).is_absolute() or ".." in parts or not parts:
            raise WtError(f"{path} lists an unsafe path ({rel!r}); delete it by hand.")
    return name, files


def _load_owned(folder: Path, name: str) -> dict[str, str]:
    """The previous manifest's {path: sha256}; refuses a folder wt did not generate."""
    claude = folder / CLAUDE_DIR
    manifest = folder / MANIFEST_REL
    if claude.is_symlink():
        raise _foreign(claude)
    if manifest.is_file():
        owner, files = _parse_manifest(manifest)
        if owner != name:
            raise _foreign(claude)
        return files
    for path in (claude, folder / CLAUDE_MD):
        if path.exists() or path.is_symlink():
            raise _foreign(path)
    return {}


def _refuse_foreign_paths(
    folder: Path, desired: Mapping[str, _Entry], old: Mapping[str, str]
) -> None:
    """A path wt wants to write that exists and is not in the old manifest belongs to the user."""

    def ours(rel: str) -> bool:
        return rel in old or any(key.startswith(f"{rel}/") for key in old)

    for rel in desired:
        path = _contained(folder, rel)
        if (path.exists() or path.is_symlink()) and not ours(rel):
            raise _foreign(path)


# --- reading the repos --------------------------------------------------------------------------


def _read_settings(path: Path) -> dict[str, Any]:
    if not path.is_file():
        return {}
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except (ValueError, OSError) as exc:
        raise WtError(f"{path} is not valid JSON ({exc}); fix it before syncing.") from exc
    if not isinstance(raw, dict):
        raise WtError(f"{path} must hold a JSON object.")
    return raw


def _skill_names(repo: str, skills_dir: Path, notes: list[str]) -> list[str]:
    names: list[str] = []
    for folder in sorted(skills_dir.glob("*")):
        if not folder.is_dir():
            continue
        if (folder / SKILL_FILE).is_file():
            names.append(folder.name)
        else:
            notes.append(f"{repo}: skill {folder.name} has no {SKILL_FILE}; skipped")
    return names


def _read_repo(repo: str, path: Path, notes: list[str]) -> RepoClaude:
    claude = path / CLAUDE_DIR
    agents = {
        file.stem: file.read_text(encoding="utf-8")
        for file in sorted((claude / "agents").glob("*.md"))
        if file.is_file()
    }
    return RepoClaude(
        repo=repo,
        agents=agents,
        skills=_skill_names(repo, claude / "skills", notes),
        settings=_read_settings(claude / "settings.json"),
        has_claude_md=(path / CLAUDE_MD).is_file(),
    )


# --- what to generate ---------------------------------------------------------------------------


def _text(kind: Kind, text: str, source: str, mode: int = FILE_MODE) -> _Entry:
    return _Entry(kind=kind, data=text.encode("utf-8"), source=source, mode=mode)


def _repo_entries(repo: RepoClaude, path: Path) -> dict[str, _Entry]:
    entries: dict[str, _Entry] = {}
    for stem, text in repo.agents.items():
        merged = merge_agent(repo.repo, stem, text, list(repo.agents), list(repo.skills))
        rel = f"{CLAUDE_DIR}/agents/{prefixed(repo.repo, stem)}.md"
        entries[rel] = _text("copy", merged, f"{repo.repo}/{CLAUDE_DIR}/agents/{stem}.md")
    for skill in repo.skills:
        target = (path / CLAUDE_DIR / "skills" / skill).absolute()
        rel = f"{CLAUDE_DIR}/skills/{prefixed(repo.repo, skill)}"
        source = f"{repo.repo}/{CLAUDE_DIR}/skills/{skill}"
        entries[rel] = _Entry(kind="link", data=str(target).encode("utf-8"), source=source)
    return entries


def _build_entries(
    name: str,
    plan_repo: str,
    repos: Mapping[str, Path],
    claude_repos: list[RepoClaude],
    merged: SettingsMerge,
) -> dict[str, _Entry]:
    entries: dict[str, _Entry] = {}
    for claude_repo in claude_repos:
        entries.update(_repo_entries(claude_repo, repos[claude_repo.repo]))
    settings = json.dumps(merged.settings, indent=2) + "\n"
    entries[f"{CLAUDE_DIR}/settings.json"] = _text("file", settings, "")
    entries[f"{CLAUDE_DIR}/{HOOK_SCRIPT_NAME}"] = _text(
        "file", HOOK_SCRIPT, "", mode=EXECUTABLE_MODE
    )
    with_md = [repo.repo for repo in claude_repos if repo.has_claude_md]
    entries[CLAUDE_MD] = _text("file", render_claude_md(name, with_md, plan_repo), "")
    return entries


def _rename_skill(text: str, new_name: str) -> str:
    """`text` with the frontmatter `name:` set to `new_name` (text without frontmatter as is)."""
    lines = text.split("\n")
    if lines[0].strip() != FRONTMATTER_FENCE:
        return text
    for index, line in enumerate(lines[1:], start=1):
        if line.strip() == FRONTMATTER_FENCE:
            break
        if line.startswith("name:"):
            lines[index] = f"name: {new_name}"
            break
    return "\n".join(lines)


# --- writing -------------------------------------------------------------------------------------


def _parents_of(rels: list[str]) -> list[str]:
    """Every folder above `rels` (below the wt folder), deepest first."""
    folders = {
        str(parent) for rel in rels for parent in PurePosixPath(rel).parents if str(parent) != "."
    }
    return sorted(folders, key=lambda folder: folder.count("/"), reverse=True)


def _prune_empty(folder: Path, removed: list[str], keep: frozenset[str] = frozenset()) -> None:
    for rel in _parents_of(removed):
        if rel in keep:
            continue
        path = folder / rel
        if path.is_dir() and not path.is_symlink() and not any(path.iterdir()):
            path.rmdir()


def _symlink_works(path: Path, target: str) -> bool:
    probe = path.parent / f".{path.name}.wt-probe"
    try:
        os.symlink(target, probe)
    except OSError:
        return False
    probe.unlink()
    return True


class _Writer:
    """Applies the wanted entries under `folder`, remembering what changed and what it wrote."""

    def __init__(self, folder: Path, old: Mapping[str, str]) -> None:
        self.folder = folder
        self.old = old
        self.changed = False
        self.written: dict[str, _Entry] = {}
        self.hand_edits: list[str] = []
        self.fallback_notes: list[str] = []

    def put(self, rel: str, entry: _Entry) -> None:
        if entry.kind == "link":
            self._put_link(rel, entry)
        else:
            self._put_file(rel, entry)

    def _put_file(self, rel: str, entry: _Entry) -> None:
        path = _contained(self.folder, rel)
        current = None if path.is_symlink() or not path.is_file() else path.read_bytes()
        if current != entry.data:
            if current is not None and rel in self.old and _sha256(current) != self.old[rel]:
                self.hand_edits.append(f"{rel} was edited by hand; replaced")
            if path.is_symlink():
                path.unlink()
            atomic_write(path, entry.data)
            self.changed = True
        if stat.S_IMODE(path.stat().st_mode) != entry.mode:
            path.chmod(entry.mode)
            self.changed = True
        self.written[rel] = entry

    def _put_link(self, rel: str, entry: _Entry) -> None:
        path = _contained(self.folder, rel)
        target = entry.data.decode("utf-8")
        if path.is_symlink():
            if os.readlink(path) == target:
                self.written[rel] = entry
                return
            path.unlink()
        elif path.is_dir():
            if not _symlink_works(path, target):
                self._copy_skill(rel, entry)
                return
            self._remove_copied_dir(rel)
        try:
            path.parent.mkdir(parents=True, exist_ok=True)
            os.symlink(target, path)
        except OSError:
            self._copy_skill(rel, entry)
            return
        self.changed = True
        self.written[rel] = entry

    def _remove_copied_dir(self, rel: str) -> None:
        prefix = f"{rel}/"
        stale = [key for key in self.old if key.startswith(prefix)]
        self._remove(stale)

    def _copy_skill(self, rel: str, entry: _Entry) -> None:
        """Fallback for a link that cannot be created: copy the skill folder, renaming it.

        The note has no OS error text so it is the same on every run (idempotent manifest)."""
        source = Path(entry.data.decode("utf-8"))
        self.fallback_notes.append(
            f"{rel}: symlinks are not available here; copied the skill folder"
        )
        for file in sorted(path for path in source.rglob("*") if path.is_file()):
            relative = file.relative_to(source).as_posix()
            data = file.read_bytes()
            if relative == SKILL_FILE:
                renamed = _rename_skill(data.decode("utf-8"), PurePosixPath(rel).name)
                data = renamed.encode("utf-8")
            self._put_file(f"{rel}/{relative}", _Entry("copy", data, f"{entry.source}/{relative}"))

    def _remove(self, rels: list[str]) -> None:
        removed: list[str] = []
        for rel in rels:
            try:
                path = _contained(self.folder, rel)
            except WtError:  # e.g. a copied skill folder that became a link into a repo
                continue
            if path.is_symlink() or path.is_file():
                path.unlink()
                removed.append(rel)
        if removed:
            self.changed = True
        _prune_empty(self.folder, removed, keep=frozenset({CLAUDE_DIR}))

    def remove_stale(self) -> None:
        self._remove([rel for rel in self.old if rel not in self.written])

    def write_manifest(self, text: str) -> None:
        path = self.folder / MANIFEST_REL
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != text:
            atomic_write(path, text)
            self.changed = True


def _manifest_text(
    name: str,
    repos: list[str],
    written: Mapping[str, _Entry],
    conflicts: list[Conflict],
    notes: list[str],
) -> str:
    files = {
        rel: {"kind": entry.kind, "sha256": _sha256(entry.data), "source": entry.source}
        for rel, entry in sorted(written.items())
    }
    manifest = {
        "version": MANIFEST_VERSION,
        "wt": name,
        "repos": repos,
        "files": files,
        "conflicts": [{"key": item.key, "repos": list(item.repos)} for item in conflicts],
        "notes": notes,
    }
    return json.dumps(manifest, indent=2) + "\n"


# --- public API -----------------------------------------------------------------------------------


def sync(
    folder: Path, name: str, repos: Mapping[str, Path], plan_repo: str | None = None
) -> ClaudeSyncResult:
    """Generate (or refresh) the merged `.claude/` and `CLAUDE.md` of a wt folder.

    `repos` maps the catalog repo name to its worktree path, in catalog order. Nothing is
    written when the folder holds files wt did not generate.
    """
    if len(repos) < MIN_REPOS:
        raise WtError(f"{name} has fewer than two repos; start Claude inside its repo folder")
    plan = plan_repo if plan_repo is not None else next(iter(repos))
    if plan not in repos:
        raise WtError(f"Plan repo {plan!r} is not one of the repos of {name}: {', '.join(repos)}.")
    old = _load_owned(folder, name)
    notes: list[str] = []
    claude_repos = [_read_repo(repo, path, notes) for repo, path in repos.items()]
    merged = merge_settings(claude_repos)
    desired = _build_entries(name, plan, repos, claude_repos, merged)
    _refuse_foreign_paths(folder, desired, old)

    writer = _Writer(folder, old)
    for rel, entry in desired.items():
        writer.put(rel, entry)
    writer.remove_stale()
    persistent = notes + writer.fallback_notes
    conflicts = list(merged.conflicts)
    text = _manifest_text(name, list(repos), writer.written, conflicts, persistent)
    writer.write_manifest(text)
    return ClaudeSyncResult(
        changed=writer.changed,
        folder=folder,
        repos=list(repos),
        agents=[
            Path(rel).stem for rel in writer.written if rel.startswith(f"{CLAUDE_DIR}/agents/")
        ],
        skills=[
            PurePosixPath(rel).name for rel in desired if rel.startswith(f"{CLAUDE_DIR}/skills/")
        ],
        conflicts=conflicts,
        notes=persistent + writer.hand_edits,
    )


def remove(folder: Path) -> list[str]:
    """Delete exactly the files and links the manifest lists, then the manifest and any
    `.claude/` folder that is left empty. Returns the relative paths removed; nothing when the
    folder has no manifest."""
    manifest = folder / MANIFEST_REL
    if not manifest.is_file():
        return []
    _, files = _parse_manifest(manifest)
    removed: list[str] = []
    for rel in sorted(files):
        try:
            path = _contained(folder, rel)
        except WtError:
            continue
        if path.is_symlink() or path.is_file():
            path.unlink()
            removed.append(rel)
    manifest.unlink()
    _prune_empty(folder, [*removed, MANIFEST_REL])
    return removed
