"""Merging the `.claude/` of several repos into one (SPEC section 29). Pure: text and dicts in, out.

Reading the repos and writing the result is the runtime layer's job (`wt.claudegen`).
"""

import json
import re
import shlex
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass
from typing import Any

HOOK_SCRIPT_NAME = "wt-hook.sh"
HOOK_COMMAND = 'bash "$CLAUDE_PROJECT_DIR/.claude/' + HOOK_SCRIPT_NAME + '" {repo} {command}'
WORK_LINE = "You work in ./{repo}/. Every path in your instructions is relative to that folder."
CLAUDE_MD_HEADER = "<!-- Generated by wt. Do not edit; run wt claude sync {wt}. -->"

# The permission rules whose parentheses hold a file path (the others hold commands, domains…).
PATH_TOOLS = frozenset({"Read", "Edit", "Write", "MultiEdit", "NotebookEdit", "Glob", "Grep"})
# A path starting like this does not depend on the folder the session starts in.
ANCHORED_PATH_STARTS = ("**/", "/", "~")
PERMISSION_LISTS = ("allow", "ask", "deny")
MERGED_SECTIONS = ("permissions", "enabledPlugins", "hooks")

# Reads stdin once, byte for byte (the sentinel keeps trailing newlines). Skips a hook whose file
# (normalized, so `..` cannot sneak out) is outside its repo; otherwise runs the original command
# as if the session started in the repo.
HOOK_SCRIPT = """#!/usr/bin/env bash
# Generated by wt. Do not edit; run wt claude sync <name>.
# Runs a repo's Claude hook as if the session had started in that repo.
# usage: wt-hook.sh <repo> <original command>
repo="$1"
cmd="$2"
input="$(cat; printf x)"
input="${input%x}"
decision="$(printf '%s' "$input" | python3 -c '
import json, os, sys
project = os.environ["CLAUDE_PROJECT_DIR"]
root = os.path.normpath(os.path.join(project, sys.argv[1]))
tool_input = json.load(sys.stdin).get("tool_input") or {}
path = tool_input.get("file_path") or tool_input.get("notebook_path")
if path and not os.path.normpath(os.path.join(project, path)).startswith(root + os.sep):
    print("skip", end="")
' "$repo" 2>/dev/null)"
[ "$decision" = skip ] && exit 0
root="$CLAUDE_PROJECT_DIR/$repo"
export CLAUDE_PROJECT_DIR="$root"
cd "$root" || exit 1
printf '%s' "$input" | bash -c "$cmd"
"""


@dataclass(frozen=True)
class RepoClaude:
    repo: str
    agents: Mapping[str, str]  # agent file stem -> file text
    skills: Sequence[str]  # skill folder names
    settings: Mapping[str, Any]  # parsed .claude/settings.json ({} when none)
    has_claude_md: bool


@dataclass(frozen=True)
class Conflict:
    key: str  # dotted path, e.g. `model` or `permissions.defaultMode`
    repos: tuple[str, ...]  # the repos that set it


@dataclass(frozen=True)
class SettingsMerge:
    settings: dict[str, Any]
    conflicts: list[Conflict]


def prefixed(repo: str, name: str) -> str:
    return f"{repo}-{name}"


# --- agents ---
FRONTMATTER_FENCE = "---"
_NAME_LINE = re.compile(r"^name:\s*(.*?)\s*$")
_KEY_LINE = re.compile(r"^(skills|agent):\s*(.*?)\s*$")
_BLOCK_ITEM = re.compile(r"^(\s*-\s+)(.*?)(\s*)$")
_BACKTICKED = re.compile(r"`([^`\n]+)`")
_FENCE_LINE = re.compile(r"^\s*(```|~~~)")


def _unquote(value: str) -> str:
    return value.strip().strip("'\"")


def _split_frontmatter(text: str) -> tuple[list[str], str]:
    """The frontmatter lines between the fences (none when absent) and the rest of the file."""
    lines = text.splitlines(keepends=True)
    if not lines or lines[0].rstrip("\r\n") != FRONTMATTER_FENCE:
        return [], text
    for end, line in enumerate(lines[1:], start=1):
        if line.rstrip("\r\n") == FRONTMATTER_FENCE:
            return lines[1:end], "".join(lines[end + 1 :])
    return [], text


def _name_pattern(names: Iterable[str]) -> re.Pattern[str] | None:
    """Whole names only: not part of a longer name, a path, a file name or `plugin:name`."""
    ordered = sorted(set(names), key=lambda n: (-len(n), n))
    if not ordered:
        return None
    alternatives = "|".join(re.escape(n) for n in ordered)
    return re.compile(rf"(?<![\w\-@:/.])(/?)({alternatives})(?![\w\-@:/]|\.\w)")


def _rewrite_ticked(line: str, pattern: re.Pattern[str] | None, mapping: Mapping[str, str]) -> str:
    """Rename the known names inside the backtick spans of one line (prose is left alone)."""
    if pattern is None:
        return line

    def inside(span: re.Match[str]) -> str:
        renamed = pattern.sub(lambda m: m.group(1) + mapping[m.group(2)], span.group(1))
        return f"`{renamed}`"

    return _BACKTICKED.sub(inside, line)


def _rewrite_items(value: str, mapping: Mapping[str, str]) -> str:
    """Rename the items of a `[a, b]` or `a, b` value, keeping quotes and spacing."""
    items = []
    for item in value.split(","):
        bare = _unquote(item)
        items.append(item.replace(bare, mapping[bare], 1) if bare in mapping else item)
    return ",".join(items)


def _rewrite_value(value: str, mapping: Mapping[str, str]) -> str:
    if value.startswith("[") and value.endswith("]"):
        return "[" + _rewrite_items(value[1:-1], mapping) + "]"
    return _rewrite_items(value, mapping)


@dataclass(frozen=True)
class _Renames:
    agents: Mapping[str, str]
    skills: Mapping[str, str]
    ticked: re.Pattern[str] | None  # backticked names of either kind
    both: Mapping[str, str]


def _renames(repo: str, agent_names: Iterable[str], skill_names: Iterable[str]) -> _Renames:
    agents = {n: prefixed(repo, n) for n in agent_names}
    skills = {n: prefixed(repo, n) for n in skill_names}
    both = {**skills, **agents}
    return _Renames(agents, skills, _name_pattern(both), both)


def _rewrite_block_item(item: re.Match[str], skills: Mapping[str, str]) -> str:
    prefix, value, tail = item.groups()
    bare = _unquote(value)
    return prefix + (value.replace(bare, skills[bare], 1) if bare in skills else value) + tail


def _rewrite_front_line(body: str, in_skill_block: bool, renames: _Renames) -> tuple[str, bool]:
    """One frontmatter line, and whether the next one may be an item of the `skills:` block."""
    item = _BLOCK_ITEM.match(body)
    if in_skill_block and item:
        return _rewrite_block_item(item, renames.skills), True
    if key := _KEY_LINE.match(body):
        return _rewrite_key(body, key, renames)
    return _rewrite_ticked(body, renames.ticked, renames.both), False


def _rewrite_frontmatter(lines: list[str], own_name: str, renames: _Renames, repo: str) -> str:
    out = [f"name: {prefixed(repo, own_name)}\n"]
    in_skill_block = False
    for line in lines:
        body = line.rstrip("\r\n")
        if _NAME_LINE.match(body):
            continue
        rewritten, in_skill_block = _rewrite_front_line(body, in_skill_block, renames)
        out.append(rewritten + line[len(body) :])
    return "".join(out)


def _rewrite_key(body: str, key: re.Match[str], renames: _Renames) -> tuple[str, bool]:
    """A `skills:` or `agent:` line, and whether a block list of skills follows it."""
    name, value = key.groups()
    mapping = renames.skills if name == "skills" else renames.agents
    if not value:
        return body, name == "skills"
    return f"{name}: {_rewrite_value(value, mapping)}", False


def _rewrite_body(text: str, renames: _Renames) -> str:
    out = []
    in_fence = False
    for line in text.splitlines(keepends=True):
        if _FENCE_LINE.match(line):
            in_fence = not in_fence
        out.append(line if in_fence else _rewrite_ticked(line, renames.ticked, renames.both))
    return "".join(out)


def merge_agent(
    repo: str, stem: str, text: str, agent_stems: Sequence[str], skill_names: Sequence[str]
) -> str:
    """One repo's agent file, ready for the merged `.claude/agents/` (SPEC section 29, item 1)."""
    front, body = _split_frontmatter(text)
    own_name = stem
    for line in front:
        if named := _NAME_LINE.match(line.rstrip("\r\n")):
            own_name = _unquote(named.group(1)) or stem
    renames = _renames(repo, [*agent_stems, own_name], skill_names)
    head = f"{FRONTMATTER_FENCE}\n{_rewrite_frontmatter(front, own_name, renames, repo)}"
    head += f"{FRONTMATTER_FENCE}\n{WORK_LINE.format(repo=repo)}\n"
    if body and not body.startswith(("\n", "\r\n")):
        head += "\n"
    return head + _rewrite_body(body, renames)


# --- settings ---
_RULE = re.compile(r"^(\w+)\((.*)\)$", re.DOTALL)


def _prefix_path(repo: str, spec: str) -> str:
    if not spec or spec.startswith(ANCHORED_PATH_STARTS):
        return spec
    relative = spec[2:] if spec.startswith("./") else spec
    return f"./{repo}/{relative}"


def _prefix_rule(repo: str, rule: str) -> str:
    """`Read(./.env)` -> `Read(./<repo>/.env)`; rules without a relative path stay as they are."""
    match = _RULE.match(rule)
    if not match or match.group(1) not in PATH_TOOLS:
        return rule
    return f"{match.group(1)}({_prefix_path(repo, match.group(2))})"


def _strings(value: Any) -> list[str]:
    return [item for item in value if isinstance(item, str)] if isinstance(value, list) else []


def _unique(items: Iterable[Any]) -> list[Any]:
    seen: set[str] = set()
    out = []
    for item in items:
        marker = json.dumps(item, sort_keys=True)
        if marker not in seen:
            seen.add(marker)
            out.append(item)
    return out


def _list(value: Any) -> list[Any]:
    return value if isinstance(value, list) else []


def _mapping(value: Any) -> Mapping[str, Any]:
    return value if isinstance(value, Mapping) else {}


def _merge_permission_lists(repos: Sequence[RepoClaude]) -> dict[str, list[str]]:
    merged = {
        kind: _unique(
            _prefix_rule(r.repo, rule)
            for r in repos
            for rule in _strings(_mapping(r.settings.get("permissions")).get(kind))
        )
        for kind in PERMISSION_LISTS
    }
    merged["allow"] = [rule for rule in merged["allow"] if rule not in merged["deny"]]  # deny wins
    return {kind: rules for kind, rules in merged.items() if rules}


def _agreed(
    values: Mapping[str, Mapping[str, Any]], prefix: str
) -> tuple[dict[str, Any], list[Conflict]]:
    """Per key: the value every repo that sets it agrees on, else a conflict.

    `values` maps a repo to its keys, in repo order.
    """
    kept: dict[str, Any] = {}
    conflicts: list[Conflict] = []
    keys = dict.fromkeys(key for mapping in values.values() for key in mapping)
    for key in keys:
        setters = {repo: mapping[key] for repo, mapping in values.items() if key in mapping}
        if len(_unique(setters.values())) == 1:
            kept[key] = next(iter(setters.values()))
        else:
            conflicts.append(Conflict(prefix + key, tuple(setters)))
    return kept, conflicts


def _merge_hooks(repos: Sequence[RepoClaude]) -> dict[str, Any]:
    groups: dict[str, dict[str | None, list[Any]]] = {}
    for r in repos:
        for event, event_groups in _mapping(r.settings.get("hooks")).items():
            for raw_group in _list(event_groups):
                group = _mapping(raw_group)
                entries = [_wrap_hook(r.repo, e) for e in _list(group.get("hooks"))]
                groups.setdefault(event, {}).setdefault(group.get("matcher"), []).extend(entries)
    return {
        event: [
            {**({} if matcher is None else {"matcher": matcher}), "hooks": _unique(entries)}
            for matcher, entries in by_matcher.items()
        ]
        for event, by_matcher in groups.items()
    }


def _wrap_hook(repo: str, entry: Any) -> Any:
    """A command hook runs through `wt-hook.sh`, so it behaves as in its own repo (section 29.4)."""
    if not isinstance(entry, Mapping) or not isinstance(entry.get("command"), str):
        return entry
    command = HOOK_COMMAND.format(repo=shlex.quote(repo), command=shlex.quote(entry["command"]))
    return {**entry, "command": command}


def _permissions_and_plugins(
    repos: Sequence[RepoClaude],
) -> tuple[dict[str, Any], list[Conflict]]:
    out: dict[str, Any] = {}
    other_permissions, conflicts = _agreed(
        {
            r.repo: {
                k: v
                for k, v in _mapping(r.settings.get("permissions")).items()
                if k not in PERMISSION_LISTS
            }
            for r in repos
        },
        "permissions.",
    )
    permissions = {**_merge_permission_lists(repos), **other_permissions}
    plugins, plugin_conflicts = _agreed(
        {r.repo: _mapping(r.settings.get("enabledPlugins")) for r in repos}, "enabledPlugins."
    )
    for key, value in (("permissions", permissions), ("enabledPlugins", plugins)):
        if value:
            out[key] = value
    return out, [*conflicts, *plugin_conflicts]


def merge_settings(repos: Sequence[RepoClaude]) -> SettingsMerge:
    """The repos' `settings.json` as one (SPEC section 29, items 3 and 4)."""
    merged, conflicts = _permissions_and_plugins(repos)
    if hooks := _merge_hooks(repos):
        merged["hooks"] = hooks
    others, other_conflicts = _agreed(
        {r.repo: {k: v for k, v in r.settings.items() if k not in MERGED_SECTIONS} for r in repos},
        "",
    )
    merged.update(others)
    return SettingsMerge(
        settings=merged, conflicts=sorted([*conflicts, *other_conflicts], key=lambda c: c.key)
    )


# --- CLAUDE.md ---
def render_claude_md(wt: str, repos_with_md: Sequence[str], plan_repo: str) -> str:
    """The generated `CLAUDE.md`: imports each repo's own, and says where the plans live."""
    lines = [CLAUDE_MD_HEADER.format(wt=wt), f"# {wt}", ""]
    if repos_with_md:
        lines += [*(f"@{repo}/CLAUDE.md" for repo in repos_with_md), ""]
    lines.append(f"Plans live in {plan_repo}/.claude/plans/<task>/.")
    return "\n".join(lines) + "\n"
